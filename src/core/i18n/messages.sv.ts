/** Union of all message keys. */
export type MessageKey = keyof typeof sv;

/** Base of a plural pair `<base>_one` / `<base>_other`, chosen by `n === 1`. */
export type PluralKey = MessageKey extends infer K
  ? K extends `${infer B}_other`
    ? B
    : never
  : never;

/** Message catalogue shape every locale must satisfy. */
export type Messages = Record<MessageKey, string>;
